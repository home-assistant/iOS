import SFSafeSymbols
import Shared
import SwiftUI

struct ThreadCredentialSharingModeView: View {
    @StateObject private var viewModel: ThreadCredentialSharingModeViewModel

    init(viewModel: ThreadCredentialSharingModeViewModel) {
        _viewModel = StateObject(wrappedValue: viewModel)
    }

    var body: some View {
        List {
            Section {
                TextField(
                    L10n.Thread.CredentialSharingMode.ExtendedPanId.placeholder,
                    text: $viewModel.extendedPANID
                )
                .font(.body.monospaced())
                .autocorrectionDisabled()
                .textInputAutocapitalization(.never)

                Button {
                    Task {
                        await viewModel.enableSharingMode()
                    }
                } label: {
                    HStack(spacing: DesignSystem.Spaces.one) {
                        Text(L10n.Thread.CredentialSharingMode.startButton)
                        if viewModel.state == .loading {
                            ProgressView()
                                .progressViewStyle(.circular)
                        }
                    }
                }
                .disabled(!viewModel.canEnableSharingMode)

                statusRow
            } header: {
                Text(L10n.Thread.ExtendedPanId.title)
            } footer: {
                Text(L10n.Thread.CredentialSharingMode.footer)
            }

            Section(L10n.Thread.CredentialSharingMode.KeychainNetworks.title) {
                if viewModel.isLoadingCredentials {
                    ProgressView()
                        .progressViewStyle(.circular)
                        .frame(maxWidth: .infinity)
                } else if viewModel.credentials.isEmpty {
                    Text(L10n.Thread.CredentialSharingMode.KeychainNetworks.empty)
                        .foregroundStyle(.secondary)
                } else {
                    ForEach(viewModel.credentials, id: \.autogeneratedId) { credential in
                        Button {
                            viewModel.select(credential)
                        } label: {
                            VStack(alignment: .leading, spacing: DesignSystem.Spaces.half) {
                                Text(credential.networkName)
                                    .foregroundStyle(Color(uiColor: .label))
                                Text(credential.extendedPANID)
                                    .font(.footnote.monospaced())
                                    .foregroundStyle(.secondary)
                            }
                        }
                    }
                }
            }
        }
        .navigationTitle(L10n.Thread.CredentialSharingMode.title)
        .navigationBarTitleDisplayMode(.inline)
        .task {
            await viewModel.loadCredentialsIfNeeded()
        }
    }

    @ViewBuilder
    private var statusRow: some View {
        switch viewModel.state {
        case .idle, .loading:
            EmptyView()
        case .success:
            Label(L10n.Thread.CredentialSharingMode.success, systemSymbol: .checkmarkCircleFill)
                .foregroundStyle(.green)
        case let .failure(message):
            Label(L10n.Thread.CredentialSharingMode.error(message), systemSymbol: .xmarkCircleFill)
                .foregroundStyle(.red)
        }
    }
}

#Preview {
    NavigationStack {
        ThreadCredentialSharingModeView(viewModel: ThreadCredentialSharingModeViewModel())
    }
}
